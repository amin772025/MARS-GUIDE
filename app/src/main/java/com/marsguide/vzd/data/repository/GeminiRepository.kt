package com.marsguide.vzd.data.repository

import com.marsguide.vzd.BuildConfig
import com.squareup.moshi.JsonClass
import com.squareup.moshi.Moshi
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

@JsonClass(generateAdapter = true)
data class GeminiRequest(val contents: List<GeminiContent>)

@JsonClass(generateAdapter = true)
data class GeminiContent(val parts: List<GeminiPart>)

@JsonClass(generateAdapter = true)
data class GeminiPart(val text: String)

@JsonClass(generateAdapter = true)
data class GeminiResponse(val candidates: List<GeminiCandidate>?)

@JsonClass(generateAdapter = true)
data class GeminiCandidate(val content: GeminiContentResponse?)

@JsonClass(generateAdapter = true)
data class GeminiContentResponse(val parts: List<GeminiPartResponse>?)

@JsonClass(generateAdapter = true)
data class GeminiPartResponse(val text: String?)

class GeminiRepository {
    private val client = OkHttpClient.Builder().build()
    private val moshi = Moshi.Builder().build()
    private val requestAdapter = moshi.adapter(GeminiRequest::class.java)
    private val responseAdapter = moshi.adapter(GeminiResponse::class.java)

    suspend fun askMarsAI(prompt: String): Result<String> = withContext(Dispatchers.IO) {
        try {
            val apiKey = BuildConfig.GEMINI_API_KEY
            if (apiKey.isBlank() || apiKey == "DEMO_KEY" || apiKey == "MY_GEMINI_API_KEY") {
                return@withContext Result.failure(Exception("Gemini API key not configured. Please add your GEMINI_API_KEY in secrets or .env."))
            }

            val url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=$apiKey"
            val geminiReq = GeminiRequest(
                contents = listOf(
                    GeminiContent(parts = listOf(GeminiPart(text = "You are VZD AI, an advanced Martian tactical astrobiology and mission guide. Provide accurate, scientific, sci-fi formatted answers to the astronaut query: $prompt")))
                )
            )

            val jsonBody = requestAdapter.toJson(geminiReq)
            val body = jsonBody.toRequestBody("application/json; charset=utf-8".toMediaType())
            val request = Request.Builder().url(url).post(body).build()

            client.newCall(request).execute().use { response ->
                if (response.code == 429) {
                    return@withContext Result.failure(Exception("429 Too Many Requests: Gemini Free Tier rate limit reached. Please wait 30 seconds before transmitting again."))
                }
                if (!response.isSuccessful) {
                    return@withContext Result.failure(Exception("Gemini API Error: ${response.code} ${response.message}"))
                }

                val responseBody = response.body?.string() ?: return@withContext Result.failure(Exception("Empty response body"))
                val geminiRes = responseAdapter.fromJson(responseBody)
                val text = geminiRes?.candidates?.firstOrNull()?.content?.parts?.firstOrNull()?.text

                if (text != null) {
                    Result.success(text)
                } else {
                    Result.failure(Exception("No content generated by Gemini AI."))
                }
            }
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
